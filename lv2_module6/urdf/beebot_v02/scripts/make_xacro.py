"""beebot.urdf -> urdf.xacro 역변환 (매크로 없는 단순본).
xacro 인자: mesh_uri(메시 경로), mock_hardware·mock_effort·port(ros2_control 하드웨어 — launch가 넘김). 기본값은 beebot.urdf에 있는 값.
출력 위치에 이 스크립트가 만들지 않은 xacro(손으로 고친 파일 등)가 있으면 덮어쓰지 않고 멈춘다.
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'beebot.urdf')
OUT = os.path.join(HERE, '..')

s = open(SRC, encoding='utf-8').read()
robot = '<robot name="beebot">'
assert robot in s, f'{robot} not found in {SRC}'
s = s.replace(robot, robot[:-1] + ' xmlns:xacro="http://www.ros.org/wiki/xacro">\n'
              '  <xacro:arg name="mesh_uri" default="package://ros_system/urdf/meshes"/>', 1)
s = s.replace('filename="meshes/', 'filename="$(arg mesh_uri)/')
# ros2_control <param> 값을 인자로 되돌린다 (원본 xacro의 인자 이름 그대로)
args = []
for param, arg in (('mock', 'mock_hardware'), ('mock_effort', 'mock_effort'), ('port', 'port')):
    pat = rf'<param name="{param}">([^<]*)</param>'
    m = re.findall(pat, s)
    assert len(m) == 1, f'<param name="{param}"> 가 1개가 아님: {m}'
    s = re.sub(pat, f'<param name="{param}">$(arg {arg})</param>', s)
    args.append(f'  <xacro:arg name="{arg}" default="{m[0]}"/>')
s = s.replace('  <xacro:arg name="mesh_uri"', '\n'.join(args) + '\n  <xacro:arg name="mesh_uri"', 1)

dst = os.path.join(OUT, 'urdf.xacro')
MARK = '<!-- generated by make_xacro.py -->'
if os.path.exists(dst) and MARK not in open(dst, encoding='utf-8').read():
    raise SystemExit(f'중단: {dst} 는 make_xacro.py가 만든 파일이 아니라 덮어쓰지 않는다')
# 왕복(xacro → urdf → xacro) 때 xacro 자동생성 머리말과 표시 주석이 쌓이지 않게 지운다
s = '\n'.join(l for l in s.split('\n') if not (l.startswith('<!-- =====') or l.startswith('<!-- |') or l == MARK))
s = s.replace('<robot ', MARK + '\n<robot ', 1)
open(dst, 'w', encoding='utf-8', newline='\n').write(s)
print('wrote', dst)
